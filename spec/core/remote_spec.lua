local remote = require("loupe.core.remote")
local edits = require("loupe.core.edits")
local clock = require("loupe.core.clock")
describe("remote inspection", function()
  local root, api, editLog, time
  before_each(function()
    root = { speed = 300, enabled = true, name = "pilot", nested = { hp = 40 } }
    root.cycle = root
    editLog = edits.new()
    time = clock.new()
    api = remote.new({
      roots = function()
        return { { name = "game", value = root } }
      end,
      edits = editLog,
      clock = time,
      setOpen = function(value)
        root.open = value
      end,
      save = function()
        return true, "saved"
      end,
    })
  end)
  it("inspects bounded tables and cycles", function()
    local value = api:call("inspect", "game", {}, nil)
    assert.equal(300, value.speed)
    assert.equal("<cycle>", value.cycle)
    assert.equal(40, api:call("inspect", "game", { "nested", "hp" }))
  end)
  it("routes writes through shared undo and rejects unsafe values", function()
    api:call("set", "game", { "speed" }, 500)
    assert.equal(500, root.speed)
    api:call("undo")
    assert.equal(300, root.speed)
    api:call("redo")
    assert.equal(500, root.speed)
    assert.has_error(function()
      api:call("set", "game", { "speed" }, "bad")
    end)
    assert.has_error(function()
      api:call("set", "game", { "speed" }, 0 / 0)
    end)
    assert.has_error(function()
      api:call("set", "game", { "missing" }, 5)
    end)
    assert.has_error(function()
      api:call("set", "game", { "nested" }, {})
    end)
    assert.has_error(function()
      api:call("set", "unknown", { "speed" }, 3)
    end)
  end)
  it("controls time without needing host update", function()
    api:call("pause")
    assert.is_true(time.paused)
    api:call("step")
    assert.equal(1, time.pendingSteps)
    api:call("resume")
    assert.is_false(time.paused)
    api:call("open")
    assert.is_true(root.open)
    api:call("close")
    assert.is_false(root.open)
    assert.is_true(api:call("save").saved)
    assert.has_error(function()
      api:call("eval")
    end)
  end)
  it("reports available roots", function()
    assert.equal("game", api:call("status").roots[1])
  end)
end)
