local collision = require("loupe.collision")
local sprites = require("loupe.sprites")
describe("game runtime helpers", function()
  it("finds swept impacts without tunneling", function()
    assert.equals(0.45, collision.sweepCircle(0, 0, 100, 0, 50, 0, 5))
    assert.is_nil(collision.sweepCircle(0, 0, 100, 0, 50, 20, 5))
    assert.equals(0, collision.sweepCircle(0, 0, 0, 0, 0, 0, 5))
    assert.is_nil(collision.sweepCircle(0, 0, 0, 0, 10, 0, 5))
    assert.is_nil(collision.sweepCircle(0, 0, 1, 0, 50, 0, 5))
  end)
  it("loops exhaust and stops one-shot explosions", function()
    assert.equals(1, sprites.frame(0, 24, 16, false))
    assert.equals(16, sprites.frame(15 / 24, 24, 16, false))
    assert.is_nil(sprites.frame(16 / 24, 24, 16, false))
    assert.equals(1, sprites.frame(16 / 24, 24, 16, true))
    assert.has_error(function()
      sprites.frame(0, 0, 16, true)
    end)
  end)
end)
